//! Generate direct validators from the pinned SDK graph, without duplicating wire declarations.

use fpas_acp::schema::{self, Version};
use std::{fmt::Write, fs, path::Path};

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let directory = Path::new(env!("CARGO_MANIFEST_DIR")).join("src/normalizers");
    for (version, module) in [(Version::V1, "v1"), (Version::V2, "v2")] {
        let definitions = schema::document(version)["$defs"]
            .as_object()
            .ok_or("missing SDK definitions")?;
        let mut names = definitions
            .keys()
            .filter(|name| name.as_str() != "ProtocolVersion")
            .collect::<Vec<_>>();
        names.sort();
        let mut text = format!(
            "//! Generated by `cargo run -p fpas-acp --example generate_normalizers`.\n\nnormalizers!({module};\n"
        );
        for name in names {
            writeln!(text, "    {name},")?;
        }
        text.push_str(");\n");
        fs::write(directory.join(format!("{module}.rs")), text)?;
    }
    Ok(())
}
