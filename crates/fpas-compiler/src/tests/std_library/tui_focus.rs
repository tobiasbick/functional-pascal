#[test]
fn std_tui_view_focus_can_be_seeded_via_host_calls() {
    let out = compile_run_with_console_events(
        "\
    program T;
    uses Std.Console, Std.Tui;

    procedure OnPaint(App: Application);
    begin
      Std.Console.WriteLn('paint')
    end;

    procedure OnActivate(App: Application);
    begin
      Std.Console.WriteLn(Application.QueryFocusedViewId(App));
      Application.HostRequestQuit(App)
    end;

    begin
      var App: Application := Application.Open();
      var First: ViewId := Application.HostRegisterView(App, 0, 0, 10, 5);
      var Second: ViewId := Application.HostRegisterView(App, 10, 0, 10, 5);
      Application.HostPushChildView(App, First);
      Application.HostPushChildView(App, Second);
      Application.HostRegisterOnPaint(App, OnPaint);
      Application.HostRegisterOnActivate(App, OnActivate);
      Application.Run(App)
    end.",
        &[ConsoleEvent::key(ConsoleKeyEvent::new(
            key_kind_index("Tab"),
            '\t',
            false,
            false,
            false,
            false,
        ))],
    );

    assert_eq!(out.lines, vec!["paint", "Some(0)"]);
}

#[test]
fn std_tui_local_view_paint_can_drive_application_run() {
    let out = compile_and_run(
        "\
program T;
uses Std.Console, Std.Tui;

procedure OnViewPaint(App: Application; ViewId: ViewId; Bounds: Std.Tui.Rect);
begin
  Std.Console.WriteLn(ViewId);
  Std.Console.WriteLn(Bounds.x);
  Std.Console.WriteLn(Bounds.y);
  Std.Console.WriteLn(Bounds.width);
  Std.Console.WriteLn(Bounds.height);
  Application.HostRequestQuit(App)
end;

begin
  var App: Application := Application.Open();
  var Parent: ViewId := Application.HostRegisterView(App, 10, 10, 20, 10);
  var Child: ViewId := Application.HostRegisterView(App, 0, 0, 1, 1);
  Application.HostSetViewParent(App, Child, Some(Parent));
  Application.HostSetViewRect(App, Child, 2, 3, 4, 2);
  Application.HostRegisterOnViewPaint(App, Child, OnViewPaint);
  Application.Run(App)
end.",
    );

    assert_eq!(out.lines, vec!["1", "12", "13", "4", "2"]);
}

// --- Tab falls through to OnKeyPressed when no views in the focus chain ---

#[test]
fn std_tui_tab_key_reaches_on_key_pressed_when_no_focusable_views() {
    let out = compile_run_with_console_events(
        "\
program T;
uses Std.Console, Std.Tui;

procedure OnPaint(App: Application);
begin
  Std.Console.WriteLn('paint')
end;

function OnKeyPressed(App: Application; Key: Std.Console.KeyEvent): boolean;
begin
  Std.Console.WriteLn('tab-key');
  Application.HostRequestQuit(App);
  return true
end;

begin
  var App: Application := Application.Open();
  var Handlers: ApplicationHandlers := record
    OnPaint := OnPaint;
    OnKeyPressed := Some(OnKeyPressed);
  end;
  Application.Configure(App, Handlers);
  Application.Run(App)
end.",
        &[ConsoleEvent::key(ConsoleKeyEvent::new(
            key_kind_index("Tab"),
            '\t',
            false,
            false,
            false,
            false,
        ))],
    );

    // No views in focus chain → Tab reaches OnKeyPressed.
    assert_eq!(out.lines, vec!["paint", "tab-key"]);
}

