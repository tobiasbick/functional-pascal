#[test]
fn std_tui_on_activate_lowers_to_intrinsic() {
    let chunk = compile_ok(
        "\
program T;
uses Std.Tui;

procedure OnPaint(App: Application); begin end;
procedure OnActivate(App: Application); begin end;

begin
  var App: Application := Application.Open();
  Application.HostRegisterOnPaint(App, OnPaint);
  Application.HostRegisterOnActivate(App, OnActivate);
  Application.Close(App)
end.",
    );

    assert!(
        chunk.code.iter().any(|op| matches!(
            op,
            Op::Intrinsic(code) if *code == u16::from(Intrinsic::Tui(TuiIntrinsic::HostRegisterOnActivate))
        )),
        "expected TuiHostRegisterOnActivate intrinsic in generated bytecode"
    );
}

