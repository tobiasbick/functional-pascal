//! `Std.Graph` bitmap text rasterization.
//!
//! **Documentation:** `docs/future/std.graph/02-pascal-surface.md`, `docs/future/std.graph/03-runtime-architecture.md` (from the repository root).

use super::backbuffer::GraphBackbuffer;

const GLYPH_WIDTH: i64 = 5;
const GLYPH_ADVANCE: i64 = 6;

/// Draws deterministic bitmap text into the runtime-owned backbuffer.
pub(crate) fn draw_text(backbuffer: &mut GraphBackbuffer, x: i64, y: i64, text: &str, color: u32) {
    let mut cursor_x = x;
    for ch in text.chars() {
        draw_glyph(backbuffer, cursor_x, y, glyph_rows(ch), color);
        cursor_x += GLYPH_ADVANCE;
    }
}

fn draw_glyph(backbuffer: &mut GraphBackbuffer, x: i64, y: i64, rows: [u8; 7], color: u32) {
    for (row_index, row_bits) in rows.into_iter().enumerate() {
        let row_index = i64::try_from(row_index).unwrap_or_default();
        for col in 0..GLYPH_WIDTH {
            let bit = 1_u8 << u32::try_from(GLYPH_WIDTH - 1 - col).unwrap_or_default();
            if row_bits & bit != 0 {
                backbuffer.put_pixel(x + col, y + row_index, color);
            }
        }
    }
}

